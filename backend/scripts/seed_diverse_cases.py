async def seed() -> None:
    _init_db()
    print(f"Connecting to database to seed {len(DIVERSE_CASES)} diverse cases...")

    async with AsyncSessionLocal() as session:
        # Clear existing cases to give a fresh, pristine presentation
        await session.execute(delete(RecoveryState))
        await session.commit()
        print("  ✓ Cleared previous recovery states")

        for idx, item in enumerate(DIVERSE_CASES, start=1):
            case_id = f"case_{idx:03d}_{uuid.uuid4().hex[:8]}"
            first_seen = NOW - timedelta(hours=item["hours_ago"])
            next_retry = (
                NOW + timedelta(hours=item["next_retry_hours"])
                if item["next_retry_hours"] is not None
                else None
            )

            audit_trail = [
                {
                    "event_triggered": f"PAYPAL.{item['case_type'].upper()}",
                    "amount": f"${item['amount']:.2f}",
                    "recovery_status": "pending",
                    "customer": {
                        "name": item["name"],
                        "email": item["email"],
                        "contact": item["contact"],
                    },
                    "channel": None,
                    "direction": "inbound",
                    "delivery_status": "received",
                    "created_at": first_seen.isoformat(),
                    "message": f"Initial failure: {item['failure_reason']}",
                }
            ]

            if item["last_action_taken"]:
                action_time = first_seen + timedelta(hours=min(item["hours_ago"] // 2, 6))
                audit_trail.append(
                    {
                        "event_triggered": f"ACTION.{item['last_action_taken'].upper()}",
                        "amount": f"${item['amount']:.2f}",
                        "recovery_status": item["recovery_status"],
                        "customer": {
                            "name": item["name"],
                            "email": item["email"],
                            "contact": item["contact"],
                        },
                        "channel": item["last_action_taken"],
                        "direction": "outbound",
                        "delivery_status": "sent" if item["recovery_status"] != "escalated" else "escalated",
                        "created_at": action_time.isoformat(),
                        "message": item["notes"],
                    }
                )

            if item["recovery_status"] == "recovered":
                audit_trail.append(
                    {
                        "event_triggered": "PAYMENT.CAPTURE.COMPLETED",
                        "amount": f"${item['amount']:.2f}",
                        "recovery_status": "recovered",
                        "customer": {
                            "name": item["name"],
                            "email": item["email"],
                            "contact": item["contact"],
                        },
                        "channel": item["last_action_taken"],
                        "direction": "inbound",
                        "delivery_status": "captured",
                        "created_at": (first_seen + timedelta(hours=item["hours_ago"] - 1)).isoformat(),
                        "message": f"Successfully captured full balance of ${item['amount']:.2f} via PayPal.",
                    }
                )

            state = RecoveryState(
                case_id=case_id,
                source_id=f"SRC-{uuid.uuid4().hex[:12]}",
                account_id="paypal_default",
                paypal_order_id=f"ORD-{uuid.uuid4().hex[:10].upper()}",
                capture_id=f"CAP-{uuid.uuid4().hex[:10].upper()}" if item["recovery_status"] == "recovered" else None,
                subscription_id=f"I-SUB{uuid.uuid4().hex[:8].upper()}" if "subscription" in item["case_type"] else None,
                invoice_id=f"INV-2026-{idx:04d}" if "invoice" in item["case_type"] else None,
                case_type=item["case_type"],
                decline_type=item["decline_type"],
                failure_reason=item["failure_reason"],
                amount=item["amount"],
                recovered_amount=item["amount"] if item["recovery_status"] == "recovered" else 0.0,
                customer={
                    "name": item["name"],
                    "email": item["email"],
                    "contact": item["contact"],
                },
                recovery_status=item["recovery_status"],
                attempt_count=item["attempt_count"],
                last_action_taken=item["last_action_taken"],
                first_seen_at=first_seen,
                next_retry_at=next_retry,
                audit_log=audit_trail,
                error_details={"failure_code": item["failure_reason"].upper()},
                case_metadata={
                    "notes": item["notes"],
                    "seeded_demo": True,
                },
            )
            session.add(state)

        await session.commit()
        print(f"  ✓ Successfully seeded {len(DIVERSE_CASES)} diverse recovery cases!")


if __name__ == "__main__":
    asyncio.run(seed())
